//! The release tree names nothing from the earlier TypeScript line (spec
//! requirement R42): six leftover terms do not occur in any tracked file
//! outside the places that have to name them.

use std::path::Path;
use std::process::Command;

/// The six terms, in lower case. Each is written in two pieces so that
/// this file does not contain them. The last one counts only when it is
/// not followed by a dot or a digit, so that a version number such as the
/// tag of a pinned action is not a hit.
fn terms() -> [String; 6] {
    [
        ["att", "est"],
        ["--fail", "-on"],
        ["bun", "x"],
        ["super", "sede"],
        ["arch", "ive"],
        ["v", "4"],
    ]
    .map(|pieces| pieces.concat())
}

/// Tracked paths that are not searched: the specification and the case
/// data define and test behaviour carried over from the earlier version,
/// the changelog carries the one note about it, the release workflow is
/// generated by the release tool, and the assets are images.
fn excluded(path: &str) -> bool {
    path.starts_with("design/")
        || path.starts_with("cases/")
        || path.starts_with("assets/")
        || path == "CHANGELOG.md"
        || path == ".github/workflows/release.yml"
}

/// The positions of `term` in `text` (lower case) that count as a hit.
fn hits(text: &str, term: &str, version_like: bool) -> Vec<usize> {
    text.match_indices(term)
        .filter(|(at, _)| {
            let next = text[at + term.len()..].chars().next();
            !(version_like && next.is_some_and(|c| c == '.' || c.is_ascii_digit()))
        })
        .map(|(at, _)| at)
        .collect()
}

#[test]
fn r42_no_tracked_file_names_a_leftover_term() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let listed = Command::new("git")
        .current_dir(&root)
        .args(["ls-files", "-z"])
        .output()
        .expect("git runs");
    assert!(listed.status.success(), "git ls-files failed");
    let terms = terms();
    let version_like = terms[5].clone();
    let mut found = Vec::new();
    let mut searched = 0;
    for path in String::from_utf8(listed.stdout)
        .expect("UTF-8 paths")
        .split('\0')
        .filter(|p| !p.is_empty() && !excluded(p))
    {
        // A file that is not UTF-8 text is a binary asset.
        let Ok(text) = std::fs::read_to_string(root.join(path)) else {
            continue;
        };
        searched += 1;
        let lower = text.to_lowercase();
        for term in &terms {
            for at in hits(&lower, term, *term == version_like) {
                let line = lower[..at].matches('\n').count() + 1;
                found.push(format!("{path}:{line}: {term}"));
            }
        }
    }
    assert!(searched > 50, "only {searched} files were searched");
    assert!(
        found.is_empty(),
        "leftover terms in tracked files:\n{}",
        found.join("\n")
    );
}

#[test]
fn the_version_like_term_is_not_a_hit_inside_a_version_number() {
    let term = terms()[5].clone();
    let text = format!("uses: x@{term}.1 and {term}5 but {term} and {term}-store");
    assert_eq!(hits(&text, &term, true).len(), 2);
    assert_eq!(hits(&text, &term, false).len(), 4);
}
